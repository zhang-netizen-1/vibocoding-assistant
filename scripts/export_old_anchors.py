"""Freeze legacy destinations from the unmodified dist, before redesign builds.

Run once after scripts/build_site.py. Never import source data or infer anchors.
The fixture is a historical contract, not a file regenerated by normal builds.
"""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit
import json
import re

ROOT = Path(__file__).resolve().parent.parent


class Ids(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids = []

    def handle_starttag(self, tag, attrs):
        value = dict(attrs).get('id')
        if value:
            self.ids.append(value)


def export(dist):
    home = (dist / 'index.html').read_text(encoding='utf-8')
    match = re.search(r'<script type="application/json" id="home-search-index">(.*?)</script>', home, re.S)
    if not match:
        raise ValueError('Requires the legacy home search index; do not regenerate after redesign')
    index = json.loads(match[1])
    entries = []
    pages = {}
    for entry in index:
        url = urlsplit(entry['href'])
        old_path = '/' + url.path.removeprefix('./').strip('/') + '/'
        if old_path not in pages:
            parser = Ids()
            parser.feed((dist / old_path.strip('/') / 'index.html').read_text(encoding='utf-8'))
            pages[old_path] = parser.ids
        if url.fragment not in pages[old_path]:
            raise ValueError(f'Missing anchor: {entry}')
        entries.append(dict(old_path=old_path, anchor=url.fragment, title=entry['title']))
    keys = {(e['old_path'], e['anchor']) for e in entries}
    if len(entries) != 189 or len(keys) != 189:
        raise ValueError('Expected exactly 189 distinct legacy search destinations')
    others = [dict(old_path=page, anchor=anchor) for page, ids in pages.items()
              for anchor in ids if (page, anchor) not in keys]
    return dict(entries=entries, non_entries=others)


if __name__ == '__main__':
    target = ROOT / 'tests/fixtures/old_anchors.json'
    if target.exists():
        raise SystemExit('Frozen fixture already exists; refusing to overwrite')
    target.write_text(json.dumps(export(ROOT / 'dist'), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Frozen 189 legacy entry anchors: {target}')
